def build_site() -> Path:
    meta = json.loads(config.MODEL_META_FILE.read_text(encoding="utf-8"))
    records = _load("monitoring_records.json")
    alerts = _load("alerts.json")
    causal = _load("causal_analysis.json")
    findings = _load("technical_findings.json")
    if not (records and alerts is not None and causal):
        raise FileNotFoundError("Run the pipeline first (python -m src.pipeline).")

    if SITE_DIR.exists():
        shutil.rmtree(SITE_DIR)
    (SITE_DIR / "assets").mkdir(parents=True)
    shutil.copytree(config.EVIDENTLY_DIR, SITE_DIR / "evidently")
    shutil.copy2(config.REPORTS_DIR / "monitoring_dashboard.html", SITE_DIR / "monitoring_dashboard.html")
    shutil.copy2(config.ROOT / "docs" / "assets" / "capa.png", SITE_DIR / "assets" / "capa.png")
    (SITE_DIR / ".nojekyll").write_text("", encoding="utf-8")
    index = SITE_DIR / "index.html"
    index.write_text(build_index(meta, records, alerts, causal, findings), encoding="utf-8")
    return index


if __name__ == "__main__":
    print(f"portal written to {build_site()}")
